# ===== 2026 官方名单 (教育部 xls) =====
wb = xlrd.open_workbook('moe_2026.xls')
s = wb.sheet_by_index(0)
targets = list(eol.keys())
prov=None
m26 = {p:[] for p in targets}
for r in range(s.nrows):
    vals=[s.cell_value(r,c) for c in range(s.ncols)]
    c0=str(vals[0]).strip()
    m=re.match(r'^(.+?)[（(]',c0)
    if m and vals[1]=='' and vals[2]=='':
        prov=m.group(1); continue
    name=str(vals[1]).strip()
    if not name: continue
    level=str(vals[5]).strip(); city=str(vals[4]).strip()
    if prov in targets and level=='专科':
        m26[prov].append((name,city))

# ===== reconcile =====
print("=== 对账 (2024 eol vs 2026 moe) ===")
for p in targets:
    e=set(n for n,_ in eol[p]); m=set(n for n,_ in m26[p])
    only_e = e-m   # 2024有,2026无 -> 升级/撤销(2024应保留)
    only_m = m-e   # 2026有,2024无 -> 2024后新增(2024不应包含)
    print(f"\n{p}: eol2024={len(e)} moe2026={len(m)} | 仅2024(升级/撤销):{len(only_e)} 仅2026(新增):{len(only_m)}")
    if only_e: print("   仅2024:", sorted(only_e))
    if only_m: print("   仅2026:", sorted(only_m))

