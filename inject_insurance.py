# ==== dry-run 锚点校验 ====
errors = []
for node, seg in pairs:
    prefix = '"' + node + '":{'
    cnt = data.count(prefix)
    if cnt != 1:
        errors.append('节点不唯一/缺失：%s count=%d' % (node, cnt))
if errors:
    for e in errors:
        print('ERROR:', e)
    sys.exit(1)
print('dry-run OK：全部 %d 个节点锚点唯一，可安全注入' % len(pairs))

# ==== 正式注入 ====
for node, seg in pairs:
    prefix = '"' + node + '":{'
    start = data.find(prefix)
    anchor = ',"source":"'
    pos = data.find(anchor, start + len(prefix))
    if pos == -1:
        print('ERROR: %s 找不到 source 锚点' % node)
        sys.exit(1)
    data = data[:pos] + ',' + seg + data[pos:]

io.open(JS, 'w', encoding='utf-8').write(data)
print('OK：已写入 %d 个节点。' % len(pairs))
